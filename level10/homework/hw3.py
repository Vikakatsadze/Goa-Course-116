#შექმენით პროგრამა, რომელიც იმუშავებს მაღაზიის სალაროს მსგავსად. მომხმარებელს უნდა შეეძლოს პროდუქტების კალათაში დამატება მათი ფასისა და რაოდენობის მითითებით. ყოველი პროდუქტის დამატებისას პროგრამამ უნდა გამოთვალოს მისი საერთო ღირებულება და დაამატოს კალათის ჯამურ თანხას. მომხმარებელს უნდა შეეძლოს პროდუქტების დამატების გაგრძელება მანამ, სანამ არ გადაწყვეტს პროცესის დასრულებას.

#გაითვალისწინეთ შემდეგი პირობები:

#- პროდუქტის ფასი და რაოდენობა დადებითი უნდა იყოს.
#- თუ კალათის ჯამური ღირებულება 100 ლარს ან მეტს მიაღწევს, მომხმარებელმა უნდა მიიღოს 10%-იანი ფასდაკლება.
#- თუ ჯამური თანხა 200 ლარს ან მეტია, ფასდაკლება უნდა იყოს 15% და არა 10%.
#- ბოლოს პროგრამამ უნდა გამოიტანოს საწყისი თანხა, ფასდაკლების ოდენობა და საბოლოო გადასახდელი თანხა.

total = 0

while True:
    answer = input("გსურს პროდუქტის დამატება? (კი/არა): ").lower()

    if answer == "არა":
        break

    elif answer == "კი":
        price = float(input("შეიყვანე პროდუქტის ფასი: "))
        quantity = int(input("შეიყვანე რაოდენობა: "))

        if price > 0 and quantity > 0:
            product_total = price * quantity
            total += product_total

            print("პროდუქტის ღირებულება:", product_total)
            print("კალათის ჯამი ამჟამად:", total)

        else:
            print("შეცდომა! ფასი და რაოდენობა დადებითი უნდა იყოს.")

    else:
        print("არასწორი არჩევანი! შეიყვანე კი ან არა.")

if total >= 200:
    discount = total * 0.15
elif total >= 100:
    discount = total * 0.10
else:
    discount = 0

final_total = total - discount

print("\n--- შეძენის შეჯამება ---")
print("საწყისი თანხა:", round(total, 2), "ლარი")
print("ფასდაკლება:", round(discount, 2), "ლარი")
print("საბოლოო გადასახდელი:", round(final_total, 2), "ლარი")