#შექმენით რიცხვის გამოცნობის თამაში, რომელშიც წინასწარ განსაზღვრული იქნება საიდუმლო რიცხვი. მომხმარებელს უნდა შეეძლოს რიცხვების შეყვანა მანამ, სანამ სწორ პასუხს არ გამოიცნობს. ყოველი მცდელობის შემდეგ პროგრამამ უნდა აცნობოს, შეყვანილი რიცხვი საიდუმლო რიცხვზე მეტია თუ ნაკლები. სწორი პასუხის გამოცნობის შემდეგ გამოიტანეთ წარმატების შეტყობინება და მცდელობების რაოდენობა.

secret_number = 25
attempts = 0

guess = int(input("გამოიცანი საიდუმლო რიცხვი: "))

while guess != secret_number:
    attempts += 1

    if guess > secret_number:
        print("შეყვანილი რიცხვი საიდუმლო რიცხვზე მეტია")
    else:
        print("შეყვანილი რიცხვი საიდუმლო რიცხვზე ნაკლებია")

    guess = int(input("სცადე თავიდან: "))

attempts += 1

print("You guessed the number!")
print("მცდელობების რაოდენობა:", attempts)