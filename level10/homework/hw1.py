#შექმენით Python-ის პროგრამა, რომელიც მომხმარებელს შეაყვანინებს ერთ მთელ რიცხვს. პროგრამამ უნდა დაადგინოს, რიცხვი დადებითია, უარყოფითია თუ ნულის ტოლი. ასევე შეამოწმეთ, რიცხვი ლუწია თუ კენტი. ბოლოს გამოიტანეთ შესაბამისი ინფორმაცია ეკრანზე.


num = int(input("შეიყვანე მთელი რიცხვი: "))

if num > 0:
    print("რიცხვი დადებითია")
elif num < 0:
    print("რიცხვი უარყოფითია")
else:
    print("რიცხვი ნულის ტოლია")

if num % 2 == 0:
    print("რიცხვი ლუწია")
else:
    print("რიცხვი კენტია")