#მომხმარებელს შეაყვანინეთ ორი რიცხვი და შეინახეთ ისინი ცვლადებში. შეამოწმეთ, პირველი რიცხვი მეტია, ნაკლებია თუ ტოლია მეორე რიცხვის. თითოეული შემოწმების შედეგი გამოიტანეთ ტერმინალში print() ფუნქციის გამოყენებით. გამოიყენეთ შედარების ოპერატორები: >, < და ==.

num1 = int(input("შეიყვანე პირველი რიცხვი: "))
num2 = int(input("შეიყვანე მეორე რიცხვი: "))

print("პირველი მეტია მეორეზე:", num1 > num2)
print("პირველი ნაკლებია მეორეზე:", num1 < num2)
print("რიცხვები ტოლია:", num1 == num2)