#შექმენით პროგრამა, რომელიც მომხმარებელს შეაყვანინებს პროდუქტის ფასსა და ასაკს. შეამოწმეთ, პროდუქტის ფასი 100 ლარზე მეტია თუ არა და მომხმარებელი მინიმუმ 18 წლისაა თუ არა. გამოიყენეთ ლოგიკური ოპერატორები and და or, რათა შეამოწმოთ სხვადასხვა პირობა და გამოიტანოთ შესაბამისი შედეგები.

price = float(input("შეიყვანე პროდუქტის ფასი: "))
age = int(input("შეიყვანე ასაკი: "))

print("ორივე პირობა სრულდება:", price > 100 and age >= 18)
print("ერთ-ერთი პირობა მაინც სრულდება:", price > 100 or age >= 18)

#აქ ორი განსხვავებული შემოწმებაა:
# and — შედეგი True იქნება მხოლოდ მაშინ, თუ პროდუქტის ფასი 100 ლარზე მეტია და მომხმარებელი მინიმუმ 18 წლისაა.
# or — შედეგი True იქნება, თუ ამ ორი პირობიდან ერთი მაინც შესრულდება.
#მაგალითად, თუ ფასი არის 150 ლარი, ხოლო ასაკი — 16:
# price > 100 and age >= 18 → False
# price > 100 or age >= 18 → True
#დაიმახსოვრე: and მოითხოვს ორივე პირობის შესრულებას, ხოლო or — მინიმუმ ერთის შესრულებას. ამ დავალებებში if და else საერთოდ არ გამოგვიყენებია.