#შეიყვანეთ ნებისმიერი მთელი დადებითი რიცხვი. თქვენი დავალებაა, პროგრამის საშუალებით დაითვალოთ ამ რიცხვის ციფრების რაოდენობა, ციფრების ჯამი და რამდენი ლუწი და კენტი ციფრია მასში. საბოლოოდ გამოიტანეთ შედეგები და დამატებით განსაზღვრეთ, ციფრების ჯამი ლუწია თუ კენტი.

number = int(input("შეიყვანეთ დადებითი მთელი რიცხვი: "))

original_number = number

count = 0
total = 0
even = 0
odd = 0

while number > 0:
    digit = number % 10

    count += 1
    total += digit

    if digit % 2 == 0:
        even += 1
    else:
        odd += 1

    number = number // 10

print("შეყვანილი რიცხვი:", original_number)
print("ციფრების რაოდენობა:", count)
print("ციფრების ჯამი:", total)
print("ლუწი ციფრების რაოდენობა:", even)
print("კენტი ციფრების რაოდენობა:", odd)

if total % 2 == 0:
    print("ციფრების ჯამი ლუწია")
else:
    print("ციფრების ჯამი კენტია")
