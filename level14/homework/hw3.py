#პროგრამაში წინასწარ განსაზღვრეთ ერთი საიდუმლო რიცხვი, მაგალითად 37. მომხმარებელს მიეცით 7 მცდელობა მის გამოსაცნობად. ყოველი მცდელობის შემდეგ პროგრამამ უნდა შეამოწმოს შეყვანილი რიცხვი და მომხმარებელს აცნობოს, საიდუმლო რიცხვი უფრო დიდია თუ უფრო პატარა. თუ მომხმარებელი სწორად გამოიცნობს, პროგრამამ უნდა შეწყვიტოს ციკლი და გამოიტანოს წარმატების შეტყობინება. თუ 7 მცდელობა ამოიწურა, გამოიტანოს შეტყობინება, რომ თამაში დასრულდა და აჩვენოს სწორი პასუხი.

secret_number = 37

attempts = 7

for i in range(attempts):

    guess = int(input("გამოიცანით საიდუმლო რიცხვი: "))

    if guess == secret_number:
        print("გილოცავთ! სწორად გამოიცანით!")
        break

    elif guess < secret_number:
        print("საიდუმლო რიცხვი უფრო დიდია!")

    else:
        print("საიდუმლო რიცხვი უფრო პატარაა!")

else:
    print("თამაში დასრულდა!")
    print("სწორი პასუხი იყო:", secret_number)