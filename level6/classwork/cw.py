#მომხმარებელს შემოაყვანინეთ 3 რიცხვი, შემდგომ გამოუტანეთ ტერმინალში ამ სამ რიცხვს შორის ყველა მათემატიკური ოპერაციის შედეგები.

num1 = float(input("შეიყვანე პირველი რიცხვი: "))
num2 = float(input("შეიყვანე მეორე რიცხვი: "))
num3 = float(input("შეიყვანე მესამე რიცხვი: "))

print("ჯამი:", num1 + num2 + num3)
print("სხვაობა:", num1 - num2 - num3)
print("ნამრავლი:", num1 * num2 * num3)

if num2 != 0 and num3 != 0:
    print("განაყოფი:", num1 / num2 / num3)
else:
    print("განაყოფი შეუძლებელია, რადგან ნულზე გაყოფა არ შეიძლება.")

print("პირველი რიცხვი მეორე რიცხვის ხარისხში:", num1 ** num2)
print("პირველი რიცხვის მეორე რიცხვზე გაყოფის ნაშთი:", num1 % num2 if num2 != 0 else "შეუძლებელია")