#მომხმარებელს შეაყვანინეთ ორი მთელი რიცხვი. შეამოწმეთ და დაბეჭდეთ შემდეგი შედარებების შედეგები:
#- პირველი რიცხვი მეტია მეორეზე თუ არა;
#- პირველი რიცხვი ნაკლებია მეორეზე თუ არა;
#- რიცხვები ერთმანეთის ტოლია თუ არა.

num1 = int(input("შეიყვანე პირველი მთელი რიცხვი: "))
num2 = int(input("შეიყვანე მეორე მთელი რიცხვი: "))

print("პირველი მეტია მეორეზე:", num1 > num2)
print("პირველი ნაკლებია მეორეზე:", num1 < num2)
print("რიცხვები ტოლია:", num1 == num2)

