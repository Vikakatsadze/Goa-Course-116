#ჩამოთვალეთ და დეტალურად ახსენით კომპიუტერის ძირითადი ნაწილები.

#1.სისტემური ბლოკი: მასში განთავსებულია კომპიუტერის მთავარი კომპონენტები, რომლებიც უზრუნველყოფენ მის მუშაობას.
#2.მონიტორი: მონიტორი ეკრანზე გამოსახავს ინფორმაციას, ტექსტს, სურათებსა და ვიდეოებს.
#3.პროცესორი: პროცესორი ასრულებს გამოთვლებს, ამუშავებს ინსტრუქციებს და მართავს კომპიუტერის მუშაობის მნიშვნელოვან პროცესებს.
#4.დედაპლატა: დედაპლატა აკავშირებს კომპიუტერის ძირითად კომპონენტებს და უზრუნველყოფს მათ შორის მონაცემების გაცვლას.