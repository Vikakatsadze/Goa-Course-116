#თქვენი დავალებაა დაწეროთ ისეთი კოდი, რომელშიც გაქვთ რიცხვების მასივი (მაგ. [1, 2, 3, 4, 5]). თქვენი დავალებაა ეს მასივი შემოაბრუნოთ, ანუ ელემენტები საპირისპირო თანმიმდევრობით დაალაგოთ, და დაბეჭდოთ შედეგი. (მაგ. ამ მასივისთვის პასუხია [5, 4, 3, 2, 1]). ასევე, არ გამოიყენოთ reverse() მეთოდი და არ შექმნათ ახალი მასივი, ელემენტები იმავე მასივში გაცვალეთ ადგილებით.

numbers = [1, 2, 3, 4, 5]

for i in range(len(numbers) // 2):
    temp = numbers[i]
    numbers[i] = numbers[len(numbers) - 1 - i]
    numbers[len(numbers) - 1 - i] = temp

print(numbers)