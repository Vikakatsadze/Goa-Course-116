#მომხმარებელს შემოატანინეთ რიცხვი თქვენი დავალებაა ნულიდან მაგ რიცხვის ჩათვლით გამოთვალოთ მხოლოდ ლუწების ჯამი (გამოიყტენეთ whle ციკლი არანაირი if-else არ გჭირდებათ).

num = int(input("შეიყვანე რიცხვი: "))

i = 0
total = 0

while i <= num:
    total += i
    i += 2

print("ლუწი რიცხვების ჯამი:", total)