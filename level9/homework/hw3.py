#შექმენით პროგრამა, რომელშიც წინასწარ განსაზღვრავთ ერთ საიდუმლო რიცხვს. მომხმარებელმა უნდა გამოიცნოს ეს რიცხვი while ციკლის გამოყენებით, იქამდე სანამ მომხმარებელი არ გამოიცნობს რიცხვს - ციკლი არ გათიშოთ და მოსთხოვეთ ყოველი შეცდომის შემდეგ რიცხვის კიდევ ერთხელ შემოყვანა, თუ გამოიცნო რიცხვი - "You guessed the number!"

secret_number = 7

guess = int(input("გამოიცანი საიდუმლო რიცხვი: "))

while guess != secret_number:
    print("არასწორია, სცადე თავიდან!")
    guess = int(input("შეიყვანე სხვა რიცხვი: "))

print("You guessed the number!")

