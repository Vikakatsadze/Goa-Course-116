#მომხმარებელს შემოაყვანინეთ ქულა, შემდგომ შეამოწმეთ ქულის დიაპაზონი და გამოუტანეთ შესაბამისი შეფასებები:

#90–100 ქულა — A
#80–89 ქულა — B
#70–79 ქულა — C
#60–69 ქულა — D
#0–59 ქულა — F

grade = int(input("შეიყვანე ქულა (0-100): "))

if grade < 0 or grade > 100:
    print("არასწორი ქულა!")
elif grade >= 90:
    print("A")
elif grade >= 80:
    print("B")
elif grade >= 70:
    print("C")
elif grade >= 60:
    print("D")
else:
    print("F")



