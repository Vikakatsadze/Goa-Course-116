#მომხმარებელს შემოაყვანინეთ 2 რიცხვი და ერთი რაიმე ოპერატორი (+, -, *, /) და ოპერატორიდან გამომდინარე მომხმარებელს გამოუტანეთ ტერმინალში მათემატიკური ოპერაციის შედეგი ამ ორ რიცხვს შორის.

num1 = float(input("შეიყვანე პირველი რიცხვი: "))
operator = input("შეიყვანე ოპერატორი (+, -, *, /): ")
num2 = float(input("შეიყვანე მეორე რიცხვი: "))

if operator == "+":
    print("შედეგი:", num1 + num2)
elif operator == "-":
    print("შედეგი:", num1 - num2)
elif operator == "*":
    print("შედეგი:", num1 * num2)
elif operator == "/":
    if num2 != 0:
        print("შედეგი:", num1 / num2)
    else:
        print("ნულზე გაყოფა შეუძლებელია!")
else:
    print("არასწორი ოპერატორი!")