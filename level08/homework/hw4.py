#მაგალითად, თუ მომხმარებელი შეიყვანს რიცხვს 5, პროგრამამ უნდა დაბეჭდოს:

#5 x 1 = 5
#5 x 2 = 10
#5 x 3 = 15
#...
#5 x 10 = 50

num = int(input("შეიყვანე მთელი რიცხვი: "))

for i in range(1, 11):
    print(num, "x", i, "=", num * i)