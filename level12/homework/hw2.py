#პროგრამამ უნდა:

#- for ციკლის გამოყენებით დაბეჭდოს ყველა ქულა;
#- დათვალოს, რამდენმა მოსწავლემ მიიღო 50 ან მეტი ქულა;
#- დათვალოს, რამდენმა მოსწავლემ მიიღო 50-ზე ნაკლები ქულა;
#- დაბეჭდოს მიღებული შედეგები.

grades = [85, 45, 90, 30, 60, 50]

passed = 0
failed = 0

print("მოსწავლეების ქულები:")

for grade in grades:
    print(grade)

    if grade >= 50:
        passed += 1
    else:
        failed += 1

print("50 ან მეტი ქულა მიიღო:", passed, "მოსწავლემ")
print("50-ზე ნაკლები ქულა მიიღო:", failed, "მოსწავლემ")