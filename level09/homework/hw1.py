#მომხმარებელს შემოაყვანინეთ რაიმე რიცხვი, თქვენი დავალებაა გაიგოთ მომხამრებლის რიცხვი დადებითია, უარყოფითი თუ ნულის ტოლი და გამოუტანეთ შესაბამისი შეტყობინება ტერმინალში ყოველი პირობისთვის.

num = float(input("შეიყვანე რიცხვი: "))

if num > 0:
    print("რიცხვი დადებითია")
elif num < 0:
    print("რიცხვი უარყოფითია")
else:
    print("რიცხვი ნულის ტოლია")


